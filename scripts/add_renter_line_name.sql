-- ═══ เก็บ "ชื่อไลน์" แยกจาก "ชื่อ-นามสกุลจริง" ═══
--
-- ปัญหาเดิม: ช่องกรอกชื่อมีช่องเดียว และระบบเติมชื่อจากโปรไฟล์ LINE ให้อัตโนมัติ
-- ซึ่งมักเป็นชื่อเล่น (เช่น "AOF") ลูกค้าก็กดผ่านโดยไม่แก้ → ร้านไม่ได้ชื่อจริงไว้ยืนยันตัวตนตอนรับเครื่อง
--
-- แก้เป็น 2 ช่อง:
--   renter_line_name = ชื่อไลน์ (เติมให้อัตโนมัติจากโปรไฟล์ ใช้จับคู่กับแชทที่คุยกันอยู่)
--   renter_name      = ชื่อ-นามสกุลจริงตามบัตรประชาชน (ลูกค้าต้องกรอกเอง ใช้ยืนยันตัวตนตอนรับเครื่อง)

alter table public.bookings
  add column if not exists renter_line_name text;

-- ข้อมูลเก่า: renter_name ที่มีอยู่คือชื่อที่เติมจาก LINE จึงคัดลอกไปไว้ช่องชื่อไลน์ด้วย
-- (ไม่ล้าง renter_name ทิ้ง เพราะเป็นข้อมูลเดียวที่มีของการจองเก่า ปล่อยไว้ให้แอดมินอ่านได้เหมือนเดิม)
update public.bookings
set renter_line_name = renter_name
where renter_line_name is null;
