-- รองรับฟีเจอร์ "เปลี่ยนรหัสผ่านแอดมิน": เก็บเวลาที่เปลี่ยนรหัสผ่านล่าสุด
-- เพื่อใช้เช็คใน requireAdmin() ว่า session (JWT) เก่าที่ออกไปก่อนหน้านี้ยังใช้ได้อยู่ไหม
-- ผลคือ: พอเปลี่ยนรหัสผ่านสำเร็จ session อื่นๆ (เช่น เครื่อง/เบราว์เซอร์ที่หลุดไปแล้ว หรือ token ที่ถูกขโมย)
-- จะถูกตัดสิทธิ์ทันทีในคำขอถัดไป ส่วน session ปัจจุบันที่กดเปลี่ยนเองจะได้ token ใหม่ให้อัตโนมัติไม่ต้อง login ซ้ำ

alter table public.admin_users
  add column if not exists password_changed_at timestamptz not null default now();

-- หมายเหตุ: หลัง deploy โค้ดที่มาพร้อม SQL นี้ admin_session (JWT) เดิมที่ login ค้างไว้ก่อนหน้านี้
-- จะไม่มีค่า pwd_ver ฝังอยู่ (ฟีเจอร์ใหม่ที่เพิ่งเพิ่ม) ระบบจะถือว่า session นั้นหมดอายุ
-- ต้อง login ใหม่ 1 ครั้ง (ทุกบัญชี) หลังจากนี้ — เป็นผลข้างเคียงที่ตั้งใจ ไม่ใช่บั๊ก
